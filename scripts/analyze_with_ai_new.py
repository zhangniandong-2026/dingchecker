import os
from datetime import datetime

from gemini_sdk import GEMINI_AVAILABLE, generate_text


def analyze_with_ai(results, target_date):
    """使用AI分析会议内容 - 优化版，输出新格式报告"""
    if not GEMINI_AVAILABLE:
        return "\n\n⚠️ Google Gemini未安装或未配置API密钥，跳过AI分析\n"

    # 检查API密钥
    api_key = os.environ.get('GEMINI_API_KEY')
    if not api_key:
        return "\n\n⚠️ 未配置GEMINI_API_KEY环境变量，跳过AI分析\n使用方法: export GEMINI_API_KEY='your-api-key'\n"

    # 只分析成功提取内容的单元
    success_results = [r for r in results if r['status'] == '成功' and r['content']]

    if len(success_results) == 0:
        return "\n\n📊 AI分析：今日无可分析内容（所有单元均无权限或无链接）\n"

    try:
        # 构建分析提示词
        content_summary = f"# {target_date} 业务单元早会语音转写内容\n\n"
        for r in success_results:
            # 限制每个单元的内容长度，避免超出token限制
            content_preview = r['content'][:3000] if len(r['content']) > 3000 else r['content']
            content_summary += f"## {r['sheet']}\n\n{content_preview}\n\n"

        # 新的prompt - 不输出转写内容，直接输出评分和建议
        prompt = f"""你是一个专业的团队管理顾问，负责评估早会质量。

请基于以下早会转写内容，按照晨会精神状态评价标准进行评估。

{content_summary}

【输出要求】

第一部分：标准早会建议（开篇）
================================================================================
钉钉早会最佳实践建议
================================================================================

📋 高效早会的五个关键要素：

1. 目标清晰 🎯
   - 用具体数字代替模糊表述（例如："完成3个客户拜访"而非"跟进客户"）
   - 明确提到客户名称、项目名称、具体金额
   - 设定明确的时间节点（"今天下午3点前"而非"尽快"）

2. 复盘闭环 🔄
   - 先汇报昨日计划的完成情况
   - 说明未完成事项的原因和调整方案
   - 形成"计划→执行→复盘→新计划"的完整循环

3. 主动协作 🤝
   - 明确提出需要的支持（"需要XX帮助我做YY"）
   - 团队成员主动响应（"我来负责"、"散会后对齐"）
   - 形成协作闭环，避免需求石沉大海

4. 聚焦重点 🔍
   - 避免单一议题占用过多时间（不超过30%）
   - 平衡覆盖所有重要事项
   - 深度讨论留到散会后1对1进行

5. 信息密度 📈
   - 分享具体的市场信息、客户需求、竞争情报
   - 避免客套话和无效寒暄
   - 每个人的发言都应该为团队带来新信息

⏰ 建议早会时长：15-20分钟
👥 建议参与方式：站立会议，提高效率
📝 建议记录方式：关键决策和行动项即时记录

第二部分：五维度评价说明
================================================================================
早会质量评价维度说明
================================================================================

本报告采用五维度评价体系，对每个业务单元的早会质量进行量化评估：

📊 评价维度：

一、目标清晰度 🎯 (1-5分)
   评价标准：
   - 5分：每个计划都有量化指标（数字、客户名、时间节点）
   - 4分：大部分计划有量化
   - 3分：部分计划有量化
   - 2分：少量计划有量化
   - 1分：全是模糊表述（"跟进"、"了解"等）

   重点关注：具体数字、客户名称、明确时间

二、复盘闭环率 🔄 (1-5分)
   评价标准：
   - 5分：完整复盘昨日所有计划
   - 4分：复盘主要计划
   - 3分：部分复盘
   - 2分：很少复盘
   - 1分：无复盘

   重点关注：计划→执行→反馈的完整闭环

三、协作敏捷度 🤝 (1-5分)
   评价标准：
   - 5分：所有求助都有即时响应
   - 4分：大部分求助有响应
   - 3分：部分求助有响应
   - 2分：响应不及时
   - 1分：无响应

   重点关注："需要支持"→"我来负责"的配对

四、问题聚焦度 🔍 (1-5分)
   评价标准：
   - 5分：议题均衡，重点突出
   - 4分：基本均衡
   - 3分：略有失衡
   - 2分：某议题占比>30%
   - 1分：严重失焦

   重点关注：时间分配的均衡性

五、信息增量 📈 (1-5分)
   评价标准：
   - 5分：信息密度高，无废话
   - 4分：信息较多
   - 3分：一般
   - 2分：信息较少
   - 1分：全是套话

   重点关注：市场信息、客户需求、竞争情报的具体性

第三部分：评分与详细分析

对每个业务单元，按以下格式输出：

一、[业务单元名称]
────────────────────────────────────────
综合得分：XX/25 (XX%) 排名：#X

🎯 目标清晰度：X分
   ✅ 优点：
      - [具体优点1]
      - [具体优点2]
   ⚠️ 待改进：
      - [具体待改进项]
      - [改进建议]

🔄 复盘闭环率：X分
   [同上格式]

🤝 协作敏捷度：X分
   [同上格式]

🔍 问题聚焦度：X分
   [同上格式]

📈 信息增量：X分
   [同上格式]

📋 改进建议（按优先级）：
   1. 🔴 高优先级：
      - [具体建议1]
      - [具体建议2]

   2. 🟡 中优先级：
      - [具体建议]

   3. 🟢 低优先级：
      - [具体建议]

────────────────────────────────────────

第四部分：综合分析与建议
================================================================================
综合分析与建议
================================================================================

📊 整体表现：

1. 综合排名：
   🥇 [单元名] - XX分 (XX%)
   🥈 [单元名] - XX分 (XX%)
   🥉 [单元名] - XX分 (XX%)
   ...

2. 单项冠军：
   🎯 目标清晰度最佳：[单元名] (X分)
   🔄 复盘闭环率最佳：[单元名] (X分)
   🤝 协作敏捷度最佳：[单元名] (X分)
   🔍 问题聚焦度最佳：[单元名] (X分)
   📈 信息增量最佳：[单元名] (X分)

3. 需要重点改进的单元：
   ⚠️ [单元名] - XX分 (XX%)
      主要问题：[问题描述]

   ⚠️ [单元名] - XX分 (XX%)
      主要问题：[问题描述]

🎯 团队层面改进建议：

1. 立即行动（本周内）：
   ✅ [具体建议1]
   ✅ [具体建议2]

2. 本月改进：
   ✅ [具体建议1]
   ✅ [具体建议2]

3. 持续优化：
   ✅ [具体建议1]
   ✅ [具体建议2]

💡 下一步行动：
   □ [行动项1]
   □ [行动项2]
   □ [行动项3]

【评估要求】
1. 严格按照5个维度评分，每个维度1-5分
2. 评分必须有明确的数据支撑和具体案例
3. 改进建议必须具体、可操作、可衡量
4. 不要输出原始转写内容，只输出评分和建议
5. 使用友好、建设性的语气
"""

        print("  正在进行AI分析...")
        analysis_text = generate_text(prompt, "gemini-2.5-flash", api_key=api_key)

        # 组装最终报告
        analysis = "\n\n" + "="*80 + "\n"
        analysis += "早会质量评估报告\n"
        analysis += "="*80 + "\n\n"
        analysis += analysis_text
        analysis += "\n\n" + "="*80 + "\n"
        analysis += "💡 报告由 DingCheck + Google Gemini AI 生成\n"
        analysis += f"生成时间：{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n"
        analysis += "="*80 + "\n"

        return analysis

    except Exception as e:
        return f"\n\n⚠️ AI分析失败: {str(e)[:200]}\n"
