#!/bin/bash
# 设置 Mac 每天 9:55 自动唤醒

echo "========================================================================"
echo "设置 Mac 自动唤醒"
echo "========================================================================"
echo ""
echo "将设置 Mac 每天 9:55 自动唤醒（为 10:00 的定时任务做准备）"
echo ""
echo "需要管理员密码..."
echo ""

sudo pmset repeat wake MTWRFSU 09:55:00

if [ $? -eq 0 ]; then
    echo ""
    echo "✅ 设置成功！"
    echo ""
    echo "验证设置："
    pmset -g sched
    echo ""
    echo "========================================================================"
    echo "💡 Mac 将在每天 9:55 自动唤醒"
    echo "💡 然后在 10:00 执行钉钉日会检查"
    echo "========================================================================"
else
    echo ""
    echo "❌ 设置失败"
    echo ""
fi
